-- Room types and nightly inventory. Rows come from db/seed/data/<tier>/room_types.csv and room_nights.csv.
-- Money is whole paise (bigint): 850000 = Rs 8,500.00

CREATE TABLE room_types (
  id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hotel_id          int NOT NULL REFERENCES hotels(id) ON DELETE CASCADE,
  name              text NOT NULL,
  max_guests        smallint NOT NULL CHECK (max_guests > 0),
  total_rooms       smallint NOT NULL CHECK (total_rooms > 0),
  base_price_paise  bigint NOT NULL CHECK (base_price_paise > 0),
  UNIQUE (hotel_id, name)             -- also serves as the index for "room types of hotel X"
);

-- One row per room type per night: that night's price and how many rooms are left.
-- Search reads it; Reserve locks these rows (in date order) and subtracts 1.
CREATE TABLE room_nights (
  room_type_id     int NOT NULL REFERENCES room_types(id) ON DELETE CASCADE,
  night            date NOT NULL,
  price_paise      bigint NOT NULL CHECK (price_paise > 0),
  available_count  int NOT NULL CHECK (available_count >= 0),  -- last line of defence against overbooking
  PRIMARY KEY (room_type_id, night)                            -- also the index search uses
);
