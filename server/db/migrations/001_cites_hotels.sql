-- Cities and hotels. Rows come from db/seed/data/<tier>/cities.csv and hotels.csv.

CREATE TABLE cities (
  id        int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      text NOT NULL UNIQUE,
  country   text NOT NULL,
  timezone  text NOT NULL               -- IANA name, e.g. 'Europe/London'; used for cancel deadlines
);

CREATE TABLE hotels (
  id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_id       int NOT NULL REFERENCES cities(id),
  name          text NOT NULL,
  address       text NOT NULL,
  lat           numeric(9,6),
  lng           numeric(9,6),
  avg_score     numeric(3,1) CHECK (avg_score BETWEEN 0 AND 10),
  review_count  int NOT NULL DEFAULT 0 CHECK (review_count >= 0),
  UNIQUE (name, address)                -- the natural key: how a re-run recognises a hotel
);

-- Search always starts with "hotels in city X". Postgres does NOT index a foreign key
-- for you, so without this, every search scans every hotel.
CREATE INDEX hotels_city_id_idx ON hotels (city_id);
